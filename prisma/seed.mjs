import "dotenv/config";
import { randomBytes, randomUUID, scryptSync } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import pg from "pg";

const { Pool } = pg;
const connectionString = process.env.DATABASE_URL;
if (!connectionString) throw new Error("DATABASE_URL is not configured.");

const pool = new Pool({ connectionString });
const credentialsPath = path.resolve("LOCAL-TEST-CREDENTIALS.md");

function hashPassword(password) {
  const salt = randomBytes(16);
  return `scrypt$${salt.toString("hex")}$${scryptSync(password, salt, 64).toString("hex")}`;
}

function createPassword() {
  return `${randomBytes(18).toString("base64url")}A7!`;
}

try {
  const seedSql = await readFile(new URL("./seed.sql", import.meta.url), "utf8");
  await pool.query(seedSql);

  const products = [
    ["PR01", "Brownies Kukus", "Kue Basah", "pcs", 35000, 277, 20, "/figma/menu-brownies.jpg"],
    ["PR02", "Bolu Gulung", "Kue Basah", "roll", 45000, 117, 10, "/figma/menu-bolu.jpg"],
    ["PR03", "Risoles Ragout", "Makanan Ringan", "pcs", 5000, 45, 50, "/figma/menu-risol.jpg"],
    ["PR04", "Pastel Isi", "Makanan Ringan", "pcs", 6000, 300, 30, "/figma/menu-pastel.jpg"],
    ["PR05", "Lapis Surabaya", "Kue Basah", "loyang", 72000, 40, 5, "/figma/menu-lapis.jpg"],
  ];
  for (const [id, name, category, unit, price, stock, minimum, image] of products) {
    await pool.query(
      `INSERT INTO produk (id_produk, nama_produk, kategori_produk, satuan_produk, harga, stok, stok_minimum, gambar_url)
       VALUES ($1, $2, $3, $4, $5, $6, $7, $8)
       ON CONFLICT (id_produk) DO UPDATE SET nama_produk = EXCLUDED.nama_produk,
         kategori_produk = EXCLUDED.kategori_produk, satuan_produk = EXCLUDED.satuan_produk,
         harga = EXCLUDED.harga, stok = EXCLUDED.stok, stok_minimum = EXCLUDED.stok_minimum,
         gambar_url = EXCLUDED.gambar_url`,
      [id, name, category, unit, price, stock, minimum, image],
    );
  }

  const demoAccounts = [
    ["rizky", "CUSTOMER", "id_pelanggan", "PLG01", "Rizky Ramadhan"],
    ["siti", "CUSTOMER", "id_pelanggan", "PLG02", "Siti Rahma"],
    ["admin", "ADMIN", "id_admin", "ADM01", "Admin Dapur"],
    ["produksi", "KARYAWAN_PRODUKSI", "id_karyawan", "KRY01", "Budi Santoso"],
    ["owner", "OWNER", "id_owner", "OWN01", "Fauziah"],
  ];
  const issued = [];
  for (const [username, role, identityColumn, identity, label] of demoAccounts) {
    const password = createPassword();
    const accountId = randomUUID();
    await pool.query(
      `INSERT INTO account (id_account, username, password_hash, role, ${identityColumn})
       VALUES ($1, $2, $3, $4::account_role, $5)
       ON CONFLICT (username) DO UPDATE SET password_hash = EXCLUDED.password_hash,
         role = EXCLUDED.role, ${identityColumn} = EXCLUDED.${identityColumn}`,
      [accountId, username, hashPassword(password), role, identity],
    );
    issued.push({ username, password, role, label });
  }

  const rows = issued
    .map(({ username, password, role, label }) =>
      `| ${label} (${role}) | \`${username}\` | \`${password}\` |`,
    )
    .join("\n");
  await writeFile(
    credentialsPath,
    `# Local test accounts\n\nGenerated by \`npm run db:seed\`. These are development-only credentials; do not copy this file into Git or use these accounts in production. Seeding again rotates these demo passwords and replaces this file.\n\n| Role / name | Username | Password |\n|---|---|---|\n${rows}\n`,
    { encoding: "utf8", mode: 0o600 },
  );
  console.log("Seed data and local test accounts are ready. Credentials are in the ignored LOCAL-TEST-CREDENTIALS.md file.");
} finally {
  await pool.end();
}
